export class PromptNotFoundError extends Error {}
export class PromptArchivedError extends Error {}

export interface GetPromptOptions {
  /** A specific past or present version, by the platform's version id. Always asks the platform. */
  version?: string;
  /** The version a label points at, such as "staging". Always asks the platform. */
  label?: string;
  /** Another word for `label`, for platforms that call labels environments. Give one or the other. */
  environment?: string;
  /** Return a prompt even if it is archived. Default false: archived prompts throw. */
  allowArchived?: boolean;
}

/** Which version of one prompt to use: a version id, or a label / environment. Not both. */
export interface PromptPin {
  version?: string;
  label?: string;
  environment?: string;
}

/**
 * Which versions `withPromptOverrides` serves inside its block, without touching the calls there.
 * `Names` narrows the keys of `prompts` when the client is typed.
 */
export interface PromptOverrides<Names extends string = string> {
  /** The label every prompt in the block is read at, unless it is pinned below or by the call itself. */
  label?: string;
  /** Another word for `label`. Give one or the other. */
  environment?: string;
  /** Per prompt: a version id or a label. */
  prompts?: Partial<Record<Names, PromptPin>>;
}

/** One pin with `environment` folded into `label`. Throws, naming `where`, when it asks for two things at once. */
function normalisePin(pin: PromptPin, where: string): { version?: string; label?: string } {
  if (pin.label !== undefined && pin.environment !== undefined && pin.label !== pin.environment) {
    throw new Error(`${where}: "label" and "environment" are the same thing; got "${pin.label}" and "${pin.environment}"`);
  }
  const label = pin.label ?? pin.environment;
  if (pin.version !== undefined && label !== undefined) {
    throw new Error(`${where}: give a version or a label, not both (version "${pin.version}", label "${label}")`);
  }
  return { ...(pin.version !== undefined ? { version: pin.version } : {}), ...(label !== undefined ? { label } : {}) };
}

/** Overrides as the client keeps them: validated, with `environment` folded into `label`. */
interface ActiveOverrides {
  label?: string;
  prompts: Record<string, { version?: string; label?: string }>;
}

/** Names of prompts that need no variables or placeholders, so their options argument may be omitted. */
type NoInputNames<P extends PromptShapes<P>> = { [K in keyof P & string]: {} extends PromptInputs<P[K]> ? K : never }[keyof P & string];
type RenderOptions<P extends PromptShapes<P>, N extends keyof P> = Omit<RenderInput, "variables" | "placeholders"> & PromptInputs<P[N]>;
type RunOptionsOf<P extends PromptShapes<P>, N extends keyof P, S extends SchemaInput | undefined> = Omit<
  RunOptions<S>,
  "variables" | "placeholders"
> &
  PromptInputs<P[N]> &
  GetPromptOptions;
type RunOutput<P extends PromptShapes<P>, N extends keyof P, S> = RunResult<S extends SchemaInput ? InferSchema<S> : P[N]["output"]>;

/**
 * `P` describes your prompts. Leave it out and names, variables and outputs are loosely typed;
 * pass the interface generated by `tas prompts types` and they are checked at compile time.
 */
export interface TasClient<P extends PromptShapes<P> = PromptMap> {
  readonly config: TasConfig;
  /** This client's masking rules. Applied to everything that leaves the process. */
  readonly mask: Masker;
  readonly prompts: {
    get(name: keyof P & string, options?: GetPromptOptions): Promise<ResolvedPrompt>;
    render<N extends NoInputNames<P>>(
      name: N,
      input?: RenderOptions<P, N>,
      options?: GetPromptOptions,
    ): Promise<{ messages: RenderedMessage[]; prompt: ResolvedPrompt }>;
    render<N extends keyof P & string>(
      name: N,
      input: RenderOptions<P, N>,
      options?: GetPromptOptions,
    ): Promise<{ messages: RenderedMessage[]; prompt: ResolvedPrompt }>;
  };
  /**
   * Fetch a prompt, render it and call the configured gateway with the prompt's model, settings,
   * tools and output schema. Pass functions in `tools` to have tool calls executed and looped.
   */
  run<N extends NoInputNames<P>, S extends SchemaInput | undefined = undefined>(
    name: N,
    options?: RunOptionsOf<P, N, S>,
  ): Promise<RunOutput<P, N, S>>;
  run<N extends keyof P & string, S extends SchemaInput | undefined = undefined>(
    name: N,
    options: RunOptionsOf<P, N, S>,
  ): Promise<RunOutput<P, N, S>>;
  /**
   * As `run`, but streamed: iterate the returned value for text and tool events as they happen,
   * and await its `result` for the same value `run` returns.
   */
  stream<N extends NoInputNames<P>, S extends SchemaInput | undefined = undefined>(
    name: N,
    options?: RunOptionsOf<P, N, S>,
  ): RunStream<RunOutput<P, N, S>["output"]>;
  stream<N extends keyof P & string, S extends SchemaInput | undefined = undefined>(
    name: N,
    options: RunOptionsOf<P, N, S>,
  ): RunStream<RunOutput<P, N, S>["output"]>;
  /** Start a multi-turn conversation from a prompt. */
  chat<N extends NoInputNames<P>>(name: N, options?: RunOptionsOf<P, N, undefined>): ChatSession;
  chat<N extends keyof P & string>(name: N, options: RunOptionsOf<P, N, undefined>): ChatSession;
  /**
   * Group work into a trace. Every `run`, `chat` turn and nested `trace` inside `fn` becomes a
   * child span. What `fn` returns is recorded as the output unless you set one.
   */
  trace<T>(name: string, fn: (span: SpanHandle) => T | Promise<T>): Promise<T>;
  trace<T>(name: string, options: TraceOptions, fn: (span: SpanHandle) => T | Promise<T>): Promise<T>;
  /**
   * Run `task` over a dataset, score each output, and report the run as an experiment to the
   * platform. The results are returned whether or not reporting succeeds.
   */
  evaluate<Input = any, Output = any, Expected = any>(
    name: string,
    options: EvaluateOptions<Input, Output, Expected>,
  ): Promise<ExperimentResult>;
  /**
   * Choose which prompt versions every call inside `fn` uses, without changing those calls: a
   * label (environment) for all of them, a version or label per prompt, or both.
   *
   *   await tas.withPromptOverrides({ environment: "staging", prompts: { "support/triage": { version: "12" } } }, handler);
   *
   * A `version`, `label` or `environment` given on a call itself wins over the block; a per-prompt
   * entry wins over the block's label; an inner block adds to an outer one. Overridden prompts are
   * always read from the platform, and one that does not exist there throws: nothing falls back to
   * another version silently. Applies to this client only, and follows async work started inside `fn`.
   */
  withPromptOverrides<T>(overrides: PromptOverrides<keyof P & string>, fn: () => T): T;
  /** Send any spans still waiting. Call before a short-lived process (script, serverless handler) exits. */
  flush(): Promise<void>;
  /** Flush and release anything this client holds. Called by the pool on eviction. */
  close(): Promise<void>;
}

/**
 * A client is a fully self-contained instance: its own platform, gateway,
 * masking rules and caches. There is no global state, so any number of
 * clients (one per tenant, per environment, per vendor) can live in one process.
 */
export function createClient<P extends PromptShapes<P> = PromptMap>(config: TasConfig): TasClient<P>;
/** From a profiles config (the shape `tas.config.ts` often has): the named profile, or its default. */
export function createClient<P extends PromptShapes<P> = PromptMap>(config: TasProfiles, profile?: string): TasClient<P>;
export function createClient<P extends PromptShapes<P> = PromptMap>(config: TasConfig | TasProfiles, profile?: string): TasClient<P> {
  return createUntypedClient(resolveProfile(config, profile).config) as unknown as TasClient<P>;
}

/** The implementation. Prompt typing is a compile-time layer over it; nothing here depends on `P`. */
function createUntypedClient(config: TasConfig): TasClient {
  const canonical = config.canonical ?? "repo";
  const defaultLabel = config.defaultLabel ?? "production";
  const ttl = config.cacheTtlMs ?? 60_000;
  const registry = config.platform.prompts;

  const local = new Map<string, PromptDefinition>();
  for (const raw of config.prompts ?? []) {
    const def = parsePrompt(raw);
    local.set(def.name, def);
  }
  const cache = new Map<string, { at: number; value: ResolvedPrompt }>();
  // Each client owns its tracer, exporters and masking, so tenants' traces can never mix.
  const exporters = (config.tracing === false ? [] : (config.tracing ?? [config.platform]))
    .map((adapter) => adapter.tracing)
    .filter((exporter): exporter is TraceExporter => exporter !== undefined);
  const mask = createMasker(config.masking);
  const tracer = new Tracer({
    exporters,
    mask,
    openTelemetry: config.openTelemetry,
    ...config.traceExport,
    ...(config.onTraceError ? { onError: config.onTraceError } : {}),
  });

  // Per client, so one tenant's overrides can never reach another tenant's calls.
  const overrides = new AsyncLocalStorage<ActiveOverrides>();

  /** What a call asks for once overrides are applied: the call itself, then its prompt's entry, then the block's label. */
  const pinFor = (name: string, options: GetPromptOptions): { version?: string; label?: string } => {
    const own = normalisePin(options, `prompt "${name}"`);
    if (own.version !== undefined || own.label !== undefined) return own;
    const scope = overrides.getStore();
    return scope?.prompts[name] ?? (scope?.label !== undefined ? { label: scope.label } : {});
  };

  const fromLocal = (name: string): ResolvedPrompt | undefined => {
    const definition = local.get(name);
    if (!definition) return undefined;
    const hash = hashPrompt(definition);
    // The lockfile says which platform version this exact content was synced as: enough to link traces to it.
    const synced = config.promptVersions?.platform === config.platform.id ? config.promptVersions.prompts[name] : undefined;
    return {
      definition,
      hash,
      source: "local",
      ...(synced?.hash === hash ? { remote: { platform: config.platform.id, version: synced.version, labels: [] } } : {}),
    };
  };

  /** Returns undefined when the platform has no such prompt; throws when the platform is unreachable. */
  const fromRemote = async (name: string, options: { version?: string; label?: string }): Promise<ResolvedPrompt | undefined> => {
    if (!registry) return undefined;
    const ref = options.version ? { name, version: options.version } : { name, label: options.label ?? defaultLabel };
    const key = JSON.stringify(ref);
    const hit = cache.get(key);
    if (hit && Date.now() - hit.at < ttl) return hit.value;
    try {
      const remote = await registry.get(ref);
      if (!remote) return undefined;
      const value: ResolvedPrompt = {
        definition: remote.definition,
        hash: hashPrompt(remote.definition),
        source: "remote",
        remote: { platform: config.platform.id, version: remote.version, labels: remote.labels },
      };
      cache.set(key, { at: Date.now(), value });
      return value;
    } catch (error) {
      if (hit) return hit.value; // stale beats down
      throw error;
    }
  };

  const get = async (name: string, options: GetPromptOptions = {}): Promise<ResolvedPrompt> => {
    // An explicit version or label is a question only the platform can answer.
    const pin = pinFor(name, options);
    const pinned = pin.version !== undefined || pin.label !== undefined;
    let found: ResolvedPrompt | undefined;
    if (canonical === "repo" && !pinned) {
      found = fromLocal(name) ?? (await fromRemote(name, pin));
    } else {
      try {
        found = await fromRemote(name, pin);
      } catch (error) {
        // Platform down: an unpinned request may fall back to the bundled snapshot.
        if (pinned || !fromLocal(name)) throw error;
      }
      if (!found && !pinned) found = fromLocal(name);
    }
    if (!found) {
      const at =
        pin.version !== undefined
          ? ` at version "${pin.version}"`
          : pin.label !== undefined
            ? ` at label "${pin.label}"`
            : // Nothing was asked for, so the platform was asked for the default label: say which, it is the usual culprit.
              registry
              ? ` at the default label "${defaultLabel}" (set \`defaultLabel\` if your platform uses another name), nor among the bundled prompts`
              : " among the bundled prompts";
      throw new PromptNotFoundError(`prompt "${name}" not found${at} (canonical: ${canonical})`);
    }
    if (found.definition.archived && !options.allowArchived) {
      throw new PromptArchivedError(
        `prompt "${name}" is archived. Remove \`archived: true\` to restore it, or pass { allowArchived: true }.`,
      );
    }
    return found;
  };

  return {
    config,
    mask,
    prompts: {
      get,
      async render(name: string, input?: RenderInput, options?: GetPromptOptions) {
        const prompt = await get(name, options);
        return { messages: renderPrompt(prompt.definition, input), prompt };
      },
    },
    async run(name: string, options: RunOptions<any> & GetPromptOptions = {}) {
      return run(config.gateway, await get(name, options), options, tracer) as never;
    },
    stream(name: string, options: RunOptions<any> & GetPromptOptions = {}) {
      return stream(config.gateway, () => get(name, options), options, tracer) as never;
    },
    chat(name: string, options: RunOptions & GetPromptOptions = {}) {
      return chat(config.gateway, () => get(name, options), options, tracer);
    },
    trace<T>(
      name: string,
      optionsOrFn: TraceOptions | ((span: SpanHandle) => T | Promise<T>),
      maybeFn?: (span: SpanHandle) => T | Promise<T>,
    ) {
      const [options, fn] = typeof optionsOrFn === "function" ? [{}, optionsOrFn] : [optionsOrFn, maybeFn!];
      return tracer.span(name, options, fn);
    },
    withPromptOverrides<T>(given: PromptOverrides, fn: () => T): T {
      const outer = overrides.getStore();
      const own = normalisePin(
        {
          ...(given.label !== undefined ? { label: given.label } : {}),
          ...(given.environment !== undefined ? { environment: given.environment } : {}),
        },
        "withPromptOverrides",
      );
      const prompts = { ...outer?.prompts };
      for (const [name, pin] of Object.entries(given.prompts ?? {})) {
        if (pin) prompts[name] = normalisePin(pin, `withPromptOverrides: prompt "${name}"`);
      }
      const label = own.label ?? outer?.label;
      return overrides.run({ ...(label !== undefined ? { label } : {}), prompts }, fn);
    },
    evaluate: (name, options) => evaluate({ platform: config.platform, mask, trace: (n, o, fn) => tracer.span(n, o, fn) }, name, options),
    flush: () => tracer.flush(),
    async close() {
      cache.clear();
      await tracer.flush();
    },
  };
}

export interface ClientPoolOptions {
  /** Look up one tenant's config: from your database, a secrets manager, a static map... */
  resolve: (key: string) => TasConfig | Promise<TasConfig>;
  /** Most clients kept alive at once; least recently used is closed first. Default 100. */
  max?: number;
}

export interface ClientPool<P extends PromptShapes<P> = PromptMap> {
  get(key: string): Promise<TasClient<P>>;
  /** Drop one tenant's client, e.g. after its credentials or platform changed. */
  evict(key: string): Promise<void>;
  close(): Promise<void>;
}

/** Lazily creates and reuses one client per key. Concurrent calls for the same key share one resolve. */
export function createClientPool<P extends PromptShapes<P> = PromptMap>(options: ClientPoolOptions): ClientPool<P> {
  const max = options.max ?? 100;
  const clients = new Map<string, Promise<TasClient<P>>>();

  const closeQuietly = async (pending: Promise<TasClient<P>>) => {
    try {
      await (await pending).close();
    } catch {
      // a client that never resolved has nothing to close
    }
  };

  return {
    get(key) {
      let pending = clients.get(key);
      if (pending) {
        clients.delete(key); // re-insert to mark as most recently used
      } else {
        pending = Promise.resolve()
          .then(() => options.resolve(key))
          .then((config) => createClient<P>(config));
        pending.catch(() => {
          if (clients.get(key) === pending) clients.delete(key); // do not cache failures
        });
      }
      clients.set(key, pending);
      while (clients.size > max) {
        const [oldestKey, oldest] = clients.entries().next().value!;
        clients.delete(oldestKey);
        void closeQuietly(oldest);
      }
      return pending;
    },
    async evict(key) {
      const pending = clients.get(key);
      clients.delete(key);
      if (pending) await closeQuietly(pending);
    },
    async close() {
      const all = [...clients.values()];
      clients.clear();
      await Promise.all(all.map(closeQuietly));
    },
  };
}

const scope = new AsyncLocalStorage<TasClient<any>>();

/** Bind a client to everything `fn` awaits, so deep code need not thread it through. */
export function withClient<T>(client: TasClient<any>, fn: () => T): T {
  return scope.run(client, fn);
}

/** The client bound by the nearest `withClient`. Throws outside one: there is deliberately no global default. */
export function currentClient<P extends PromptShapes<P> = PromptMap>(): TasClient<P> {
  const client = scope.getStore();
  if (!client) throw new Error("no tas client in scope: wrap the request in withClient(client, fn)");
  return client;
}
