/**
 * Typed prompts: the generator's output, and that a client typed with it rejects wrong names,
 * missing variables and wrong placeholders at compile time. The compile-time half is checked twice:
 * by `// @ts-expect-error` lines here (run by `pnpm typecheck`), and by compiling generated code.
 */
import { execFile } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { promisify } from "node:util";
import { describe, expect, it } from "vitest";
import { createClient, generatePromptTypes, jsonSchemaToType, memory, writePrompt, type PromptDefinition, type TemplateValue } from "../src/index.ts";

const prompts: PromptDefinition[] = [
  {
    type: "chat",
    name: "support/triage",
    description: "Routes a ticket */ safely",
    messages: [{ role: "system", content: "For {{company}}." }, { placeholder: "history" }, { role: "user", content: "{{ticket.body}} from {{ticket.author.name}}" }],
    output: { schema: { type: "object", properties: { queue: { type: "string", enum: ["billing", "tech"] }, urgent: { type: "boolean" } }, required: ["queue"] } },
  },
  { type: "text", name: "greeting", text: "Hello." },
  { type: "text", name: "odd-names", text: "{{first_name}} {{a.b-c}}" },
];

describe("generating prompt types", () => {
  it("writes one entry per prompt with nested variables, placeholders and output", () => {
    expect(generatePromptTypes(prompts)).toBe(`// Generated by \`tas prompts types\` from the prompt files. Do not edit: re-run the command instead.
import type { TemplateValue } from "@traceandscale/sdk";

export interface Prompts {
  "greeting": {
    variables: {};
    placeholders: never;
    output: unknown;
  };
  "odd-names": {
    variables: {
      first_name: TemplateValue;
    };
    placeholders: never;
    output: unknown;
  };
  /** Routes a ticket * / safely */
  "support/triage": {
    variables: {
      company: TemplateValue;
      ticket: {
        body: TemplateValue;
        author: {
          name: TemplateValue;
        };
      };
    };
    placeholders: "history";
    output: {
      queue: "billing" | "tech";
      urgent?: boolean;
    };
  };
}
`);
  });

  it("honours the sdk path and interface name options", () => {
    const source = generatePromptTypes([], { sdk: "../sdk.ts", name: "AcmePrompts" });
    expect(source).toContain('from "../sdk.ts"');
    expect(source).toContain("export interface AcmePrompts {\n}");
  });

  it.each([
    [{ type: "string" }, "string"],
    [{ type: "integer" }, "number"],
    [{ type: ["string", "null"] }, "string | null"],
    [{ const: 3 }, "3"],
    [{ enum: [] }, "never"],
    [{ type: "array", items: { type: "string" } }, "string[]"],
    [{ type: "array", items: { enum: ["a", "b"] } }, '("a" | "b")[]'],
    [{ anyOf: [{ type: "number" }, { type: "boolean" }] }, "number | boolean"],
    [{ type: "object" }, "Record<string, unknown>"],
    [{ type: "object", properties: { "needs-quotes": { type: "null" } } }, '{\n  "needs-quotes"?: null;\n}'],
    [{ $ref: "#/defs/x" }, "unknown"],
    [undefined, "unknown"],
  ])("jsonSchemaToType(%j) is %s", (schema, expected) => {
    expect(jsonSchemaToType(schema)).toBe(expected);
  });
});

/** What the generator emits for `prompts`, written out so the type checks below run under `pnpm typecheck`. */
interface Prompts {
  greeting: { variables: {}; placeholders: never; output: unknown };
  "support/triage": {
    variables: { company: TemplateValue; ticket: { body: TemplateValue; author: { name: TemplateValue } } };
    placeholders: "history";
    output: { queue: "billing" | "tech"; urgent?: boolean };
  };
}

// Never called: its purpose is to be type-checked.
export async function compileTimeChecks() {
  const tas = createClient<Prompts>({ platform: memory() });
  const variables = { company: "Acme", ticket: { body: "x", author: { name: "Jo" } } };

  await tas.run("greeting");
  const result = await tas.run("support/triage", { variables, placeholders: { history: [] } });
  const queue: "billing" | "tech" = result.output.queue; // typed from the prompt's output schema
  tas.chat("greeting");
  await tas.prompts.render("support/triage", { variables, placeholders: { history: [] } });

  // @ts-expect-error unknown prompt name
  await tas.run("support/triag");
  // @ts-expect-error this prompt needs variables, so options cannot be omitted
  await tas.run("support/triage");
  // @ts-expect-error a variable is missing
  await tas.run("support/triage", { variables: { company: "Acme" }, placeholders: { history: [] } });
  // @ts-expect-error a nested variable is missing
  await tas.run("support/triage", { variables: { company: "Acme", ticket: { body: "x" } }, placeholders: { history: [] } });
  // @ts-expect-error the placeholder is missing
  await tas.run("support/triage", { variables });
  // @ts-expect-error not a placeholder of this prompt
  await tas.run("support/triage", { variables, placeholders: { history: [], extra: [] } });
  // @ts-expect-error undefined is not a value a variable can take
  await tas.run("support/triage", { variables: { ...variables, company: undefined }, placeholders: { history: [] } });
  // @ts-expect-error this prompt has no placeholders
  await tas.run("greeting", { placeholders: { history: [] } });
  // @ts-expect-error unknown prompt name
  tas.chat("nope");

  // Without the type parameter everything is loose, as before.
  const loose = createClient({ platform: memory() });
  await loose.run("anything", { variables: { whatever: 1 }, placeholders: { any: [] } });
  await loose.run("anything");
  return queue;
}

describe("generated types against the compiler", () => {
  it("the generated file compiles, and enforces names and variables", async () => {
    // Inside the project so the compiler finds its own type roots.
    const dir = await mkdtemp(join(resolve("test"), ".types-"));
    try {
      const sdk = resolve("src/index.ts");
      await writeFile(join(dir, "prompts.ts"), generatePromptTypes(prompts, { sdk }));
      await writeFile(
        join(dir, "use.ts"),
        `import { createClient, memory } from ${JSON.stringify(sdk)};\nimport type { Prompts } from "./prompts.ts";\n` +
          `const tas = createClient<Prompts>({ platform: memory() });\n` +
          `export const ok = tas.run("support/triage", { variables: { company: "A", ticket: { body: "b", author: { name: "n" } } }, placeholders: { history: [] } });\n` +
          `export const badName = tas.run("support/nope");\n` +
          `export const missingVariable = tas.run("support/triage", { variables: { company: "A" }, placeholders: { history: [] } });\n`,
      );
      const tsc = resolve("node_modules/.bin/tsc");
      const args = ["--ignoreConfig", "--noEmit", "--strict", "--target", "ES2023", "--module", "NodeNext", "--moduleResolution", "NodeNext", "--allowImportingTsExtensions", "--skipLibCheck", "--types", "node", join(dir, "use.ts")];
      const output = await promisify(execFile)(tsc, args, { cwd: resolve(".") }).then(
        (r) => r.stdout,
        (e: { stdout: string }) => e.stdout,
      );
      const errorLines = output.split("\n").filter((line) => line.includes("error TS")).map((line) => Number(/use\.ts\((\d+),/.exec(line)?.[1]));
      expect(errorLines).toEqual([5, 6]); // exactly the two deliberate mistakes, nothing in the generated file
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  }, 60_000);

  it("tas prompts types writes prompts.ts from the prompt files", async () => {
    const dir = await mkdtemp(join(resolve("test"), ".types-cli-"));
    try {
      await writeFile(join(dir, "tas.config.ts"), `import { defineConfig, memory } from ${JSON.stringify(resolve("src/index.ts"))};\nexport default defineConfig({ platform: memory(), promptsDir: "p" });\n`);
      for (const prompt of prompts) await writePrompt(join(dir, "p"), prompt);
      const { stdout } = await promisify(execFile)(process.execPath, [resolve("src/cli.ts"), "prompts", "types"], { cwd: dir });
      expect(stdout).toMatch(/wrote .*p\/prompts\.ts \(3 prompts\)/);
      expect(await readFile(join(dir, "p", "prompts.ts"), "utf8")).toBe(generatePromptTypes(prompts));
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
});
